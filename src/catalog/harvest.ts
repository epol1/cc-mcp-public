// `aec effects --refresh`: describes every vanilla effect (one eval each, resumable) into
// src/catalog/params.json, then generates src/dsl/effects.generated.ts (typed params + popup labels).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { callRuntime } from '../bridge/index.ts';
import { aeWindows, autoAnswerKnown } from '../bridge/dialogs.ts';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const PARAMS = path.join(DIR, 'params.json');
const GEN = path.join(DIR, '../dsl/effects.generated.ts');

/** Effects that open dialogs, launch apps or start analysis when applied: never applied by the harvester. */
// Effects that open a modal dialog (file picker, options, analysis) when applied from a script.
export const HARVEST_BLOCKLIST = new Set(['CINEMA 4D Effect', 'mochaAECC', 'ADBE 3D Tracker', 'ADBE Apply Color LUT2', 'ADBE SubspaceStabilizer', 'ADBE Numbers2']);

export async function harvest(opts: { only?: string[]; force?: boolean; log?: (s: string) => void; timeoutMs?: number } = {}): Promise<{ done: number; failed: string[] }> {
  const log = opts.log ?? ((s: string) => console.log(s));
  const list: [string, string, string][] = JSON.parse(fs.readFileSync(path.join(DIR, 'effects.json'), 'utf8')).effects;
  const db: Record<string, any> = fs.existsSync(PARAMS) ? JSON.parse(fs.readFileSync(PARAMS, 'utf8')) : {};
  const failed: string[] = [];
  let done = 0;
  for (const [mn, name, cat] of list) {
    if (opts.only && !opts.only.includes(mn)) continue;
    if (db[mn] && !opts.only && !opts.force) { done++; continue; }
    if (HARVEST_BLOCKLIST.has(mn)) { db[mn] = { name, category: cat, skipped: 'opens a dialog/analysis on apply' }; continue; }
    try {
      const r = await callRuntime('describeEffect', [mn], { timeoutMs: opts.timeoutMs ?? 30_000, cancelDialogs: true });
      if (r.cancelledDialogs) log(`${mn}: cancelled dialog(s) ${r.cancelledDialogs.join(', ')}`);
      if (!r.ok) throw new Error(r.error);
      db[mn] = { name, category: cat, params: r.params.map((p: any) => ({ i: p.index, n: p.name, mn: p.mn, t: p.type, d: p.default, min: p.min, max: p.max, g: p.group, o: p.options, l: p.layerRef || undefined })) };
      done++;
      if (done % 20 === 0) log(`… ${done} effects`);
    } catch (e: any) {
      failed.push(`${mn}: ${e.message}`);
      db[mn] = { name, category: cat, skipped: e.message.slice(0, 200) };
      const w = await aeWindows().catch(() => null);
      if (w?.dialogs.length) { await autoAnswerKnown(w); log(`dialog after ${mn}; answer it with aec dialogs`); }
    }
    fs.writeFileSync(PARAMS, JSON.stringify(db));
  }
  generateTypes(db);
  return { done, failed };
}

const q = (s: string) => JSON.stringify(s);

/** Writes typed effect params: display-name keys, numbers or popup labels, colors as strings. */
export function generateTypes(db?: Record<string, any>): void {
  db ??= JSON.parse(fs.readFileSync(PARAMS, 'utf8'));
  const lines = ['// GENERATED by src/catalog/harvest.ts from the installed After Effects (vanilla effects only). Do not edit.', '/* eslint-disable */', 'type Anim = import("./anim.ts").Anim;', 'type Ctl = import("./control.ts").ControlRef;', 'type V<T> = T | Anim | Ctl;', 'export interface EffectParams {'];
  const seen = new Set<string>();
  for (const [mn, e] of Object.entries(db!)) {
    if (!e.params) continue;
    const fields: string[] = [];
    const names = new Set<string>();
    for (const p of e.params) {
      // Repeated display names (Keylight's two "Replace Method"s) are keyed by matchName after the first.
      const key = names.has(p.n) ? p.mn : p.n;
      names.add(p.n);
      let t = 'V<number>';
      if (p.t === 'COLOR') t = 'V<string | number[]>';
      else if (p.t === 'TwoD' || p.t === 'TwoD_SPATIAL') t = 'V<[number, number]>';
      else if (p.t === 'ThreeD' || p.t === 'ThreeD_SPATIAL') t = 'V<[number, number, number]>';
      else if (p.l) t = '{ layer: string }';
      if (p.o && p.o.length) t = `V<number> | ${p.o.map((o: string) => q(o.replace(/^\d+=/, ''))).filter((o: string) => !o.includes('(-')).join(' | ')}`;
      const doc = `${p.g ? p.g + ' › ' : ''}${p.n}${p.d !== undefined ? ` (default ${JSON.stringify(p.d)})` : ''}${p.min !== undefined && p.max !== undefined && p.min > -1e6 ? ` [${p.min}..${p.max}]` : ''}`;
      fields.push(`    /** ${doc.replace(/\*\//g, '')} */\n    ${q(key)}?: ${t};`);
    }
    const body = `{\n${fields.join('\n')}\n  }`;
    if (seen.has(mn)) continue;
    seen.add(mn);
    lines.push(`  /** ${e.name} (${e.category}) */`, `  ${q(mn)}: ${body};`);
    if (e.name !== mn && !seen.has(e.name) && !db![e.name]) { seen.add(e.name); lines.push(`  ${q(e.name)}: EffectParams[${q(mn)}];`); }
  }
  lines.push('}', 'export type EffectName = keyof EffectParams;', '');
  fs.writeFileSync(GEN, lines.join('\n'));
}

let DB: Record<string, any> | null = null;

/** Harvested min/max of an effect parameter (by display name or matchName), when known. */
export function paramRange(effectMn: string, param: string): { min: number; max: number } | undefined {
  if (!DB) DB = fs.existsSync(PARAMS) ? JSON.parse(fs.readFileSync(PARAMS, 'utf8')) : {};
  const p = DB![effectMn]?.params?.find((x: any) => x.n === param || x.mn === param);
  return p && typeof p.min === 'number' && typeof p.max === 'number' ? { min: p.min, max: p.max } : undefined;
}

/** Popup label → index using the harvested catalog ("Screen" → 6). Returns undefined when unknown. */
export function popupIndex(effectMn: string, param: string, label: string): number | undefined {
  if (!DB) DB = fs.existsSync(PARAMS) ? JSON.parse(fs.readFileSync(PARAMS, 'utf8')) : {};
  const p = DB![effectMn]?.params?.find((x: any) => x.n === param || x.mn === param);
  const o = p?.o?.find((s: string) => s.replace(/^\d+=/, '').toLowerCase() === label.toLowerCase());
  return o ? parseInt(o, 10) : undefined;
}
